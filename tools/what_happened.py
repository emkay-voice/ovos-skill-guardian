for lang, (intent, *rest) in T.items():
    *dialogs, example = rest
    loc = Path("locale", lang)
    (loc / "what_happened.intent").write_text("\n".join(intent) + "\n", encoding="utf-8")
    for name, lines in zip(DIALOGS, dialogs):
        (loc / f"{name}.dialog").write_text("\n".join(lines) + "\n", encoding="utf-8")
    sj = loc / "skill.json"
    meta = json.loads(sj.read_text(encoding="utf-8"))
    if example not in meta["examples"]:
        meta["examples"].insert(2, example)
    sj.write_text(json.dumps(meta, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
